-- ============================================================
-- 15. PAYMENTS
-- Thanh toan gia lap: COD hoac MOCK_BANKING.
-- ============================================================

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    order_id BIGINT NOT NULL,

    method VARCHAR(30) NOT NULL DEFAULT 'COD',
