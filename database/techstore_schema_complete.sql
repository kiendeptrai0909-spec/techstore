);

COMMENT ON TABLE faqs IS 'Luu danh sach cau hoi thuong gap';

-- ============================================================
-- 21. CONTACT MESSAGES
-- Form lien he cua khach hang.
-- ============================================================

CREATE TABLE contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(20),

    subject VARCHAR(255),
    message TEXT NOT NULL,

    status VARCHAR(30) NOT NULL DEFAULT 'NEW',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_contact_messages_status
        CHECK (status IN ('NEW', 'PROCESSING', 'RESOLVED'))
);

COMMENT ON TABLE contact_messages IS 'Luu thong tin khach hang gui qua form lien he';

-- ============================================================
-- 22. CHAT SESSIONS
-- Chat ho tro dang REST API, chua bat buoc realtime WebSocket.
-- ============================================================

CREATE TABLE chat_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    customer_id BIGINT NOT NULL,
    staff_id BIGINT,

    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMP,

    CONSTRAINT chk_chat_sessions_status
        CHECK (status IN ('OPEN', 'CLOSED')),

    CONSTRAINT fk_chat_sessions_customer
        FOREIGN KEY (customer_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_chat_sessions_staff
        FOREIGN KEY (staff_id)
        REFERENCES users(id)
        ON DELETE SET NULL
);

COMMENT ON TABLE chat_sessions IS 'Luu phien chat ho tro giua khach hang va nhan vien';

-- ============================================================
-- 23. CHAT MESSAGES
-- Tin nhan trong phien chat.
-- ============================================================

CREATE TABLE chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    session_id BIGINT NOT NULL,
    sender_id BIGINT NOT NULL,

    message TEXT NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_chat_messages_session
        FOREIGN KEY (session_id)
        REFERENCES chat_sessions(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_chat_messages_sender
        FOREIGN KEY (sender_id)
        REFERENCES users(id)
        ON DELETE RESTRICT
);

COMMENT ON TABLE chat_messages IS 'Luu tin nhan trong tung phien chat';

