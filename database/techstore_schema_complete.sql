-- ============================================================
-- 12. COUPONS
-- Ma giam gia: PERCENTAGE hoac FIXED.
-- ============================================================

CREATE TABLE coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description TEXT,

    discount_type VARCHAR(20) NOT NULL,
    discount_value NUMERIC(12, 2) NOT NULL,

    min_order_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    max_discount_amount NUMERIC(12, 2),

    usage_limit INT,
    used_count INT NOT NULL DEFAULT 0,

    start_at TIMESTAMP,
    end_at TIMESTAMP,

    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP,

    CONSTRAINT chk_coupons_discount_type
        CHECK (discount_type IN ('PERCENTAGE', 'FIXED')),

    CONSTRAINT chk_coupons_discount_value
        CHECK (
            (discount_type = 'PERCENTAGE' AND discount_value > 0 AND discount_value <= 100)
            OR
            (discount_type = 'FIXED' AND discount_value > 0)
        ),

    CONSTRAINT chk_coupons_min_order_amount
        CHECK (min_order_amount >= 0),

    CONSTRAINT chk_coupons_max_discount_amount
        CHECK (max_discount_amount IS NULL OR max_discount_amount >= 0),

    CONSTRAINT chk_coupons_usage_limit
        CHECK (usage_limit IS NULL OR usage_limit >= 0),

    CONSTRAINT chk_coupons_used_count
        CHECK (used_count >= 0),

    CONSTRAINT chk_coupons_used_count_limit
        CHECK (usage_limit IS NULL OR used_count <= usage_limit),

    CONSTRAINT chk_coupons_date_range
        CHECK (start_at IS NULL OR end_at IS NULL OR end_at >= start_at),

    CONSTRAINT chk_coupons_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'EXPIRED'))
);

COMMENT ON TABLE coupons IS 'Luu thong tin ma giam gia';
COMMENT ON COLUMN coupons.discount_type IS 'PERCENTAGE, FIXED';

-- ============================================================
-- 13. ORDERS
-- Luu thong tin tong quat cua don hang.
-- Payment duoc tach sang bang payments.
-- ============================================================

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,
    coupon_id BIGINT,
    coupon_code VARCHAR(50),

    order_code VARCHAR(50) NOT NULL,

    subtotal_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    shipping_fee NUMERIC(12, 2) NOT NULL DEFAULT 0,
    discount_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    final_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,

    order_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',

    receiver_name VARCHAR(100) NOT NULL,
    receiver_phone VARCHAR(20) NOT NULL,
    shipping_address TEXT NOT NULL,

    note TEXT,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP,

    CONSTRAINT uq_orders_order_code UNIQUE (order_code),

    CONSTRAINT chk_orders_subtotal_amount
        CHECK (subtotal_amount >= 0),

    CONSTRAINT chk_orders_shipping_fee
        CHECK (shipping_fee >= 0),

    CONSTRAINT chk_orders_discount_amount
        CHECK (discount_amount >= 0),

    CONSTRAINT chk_orders_final_amount
        CHECK (final_amount >= 0),

    CONSTRAINT chk_orders_order_status
        CHECK (order_status IN ('PENDING', 'CONFIRMED', 'SHIPPING', 'COMPLETED', 'CANCELLED')),

    CONSTRAINT fk_orders_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_orders_coupon
        FOREIGN KEY (coupon_id)
        REFERENCES coupons(id)
        ON DELETE SET NULL
);

COMMENT ON TABLE orders IS 'Luu thong tin don hang';
COMMENT ON COLUMN orders.subtotal_amount IS 'Tong tien hang truoc giam gia va phi van chuyen';
COMMENT ON COLUMN orders.final_amount IS 'So tien khach can thanh toan sau giam gia va phi van chuyen';
COMMENT ON COLUMN orders.order_status IS 'PENDING, CONFIRMED, SHIPPING, COMPLETED, CANCELLED';

