-- ============================================================
-- 5. PRODUCTS
-- Thong tin chung cua san pham. Gia va ton kho nam o product_variants.
-- ============================================================

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    category_id BIGINT NOT NULL,
    brand_id BIGINT,

