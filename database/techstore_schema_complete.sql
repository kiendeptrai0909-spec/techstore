-- ============================================================
-- 6. PRODUCT VARIANTS
-- Moi bien the co SKU, gia, gia khuyen mai va ton kho rieng.
-- ============================================================

CREATE TABLE product_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL,

    name VARCHAR(150) NOT NULL,
    sku VARCHAR(100) NOT NULL,

    price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    sale_price NUMERIC(12, 2),
    sale_start_at TIMESTAMP,
    sale_end_at TIMESTAMP,

    stock INT NOT NULL DEFAULT 0,
    thumbnail_url TEXT,

    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP,

    CONSTRAINT uq_product_variants_sku UNIQUE (sku),

    CONSTRAINT chk_product_variants_price
        CHECK (price >= 0),

    CONSTRAINT chk_product_variants_sale_price
        CHECK (sale_price IS NULL OR sale_price >= 0),

    CONSTRAINT chk_product_variants_sale_price_lte_price
        CHECK (sale_price IS NULL OR sale_price <= price),

    CONSTRAINT chk_product_variants_sale_date
        CHECK (sale_start_at IS NULL OR sale_end_at IS NULL OR sale_end_at >= sale_start_at),

    CONSTRAINT chk_product_variants_stock
        CHECK (stock >= 0),

    CONSTRAINT chk_product_variants_status
        CHECK (status IN ('ACTIVE', 'INACTIVE')),

    CONSTRAINT fk_product_variants_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE RESTRICT
);

COMMENT ON TABLE product_variants IS 'Luu cac phien ban cu the cua san pham, co SKU, gia va ton kho rieng';
COMMENT ON COLUMN product_variants.sale_price IS 'Gia khuyen mai cua bien the, neu co';

